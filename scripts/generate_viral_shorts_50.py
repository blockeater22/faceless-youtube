def build(idx, t):
    cfg = NICHE[t["niche"]]
    c1, c2, c3, c4 = (PALETTE[idx % 5], PALETTE[(idx + 1) % 5],
                      PALETTE[(idx + 2) % 5], PALETTE[(idx + 3) % 5])
    style = DARK_STYLE if idx % 2 else LIGHT_STYLE
    hook_icon = cfg["hook_icons"][idx % len(cfg["hook_icons"])]
    sc1, sc2, sc3 = cfg["scenery"]
    cta_line = CTA_TEMPLATES[idx % len(CTA_TEMPLATES)].format(c=t["comment"])

    pos = [0.5, 0.22]
    scenes = [
        scene("01_hook", t["hook"], "surprised",
              [icon_prop(hook_icon, pos, 0.16, c1)], 4.2, idx * 6 + 0),
        scene("02_promise", t["promise"], "think",
              [icon_prop(cfg["promise_icon"], pos, 0.16, c2)], 4.2, idx * 6 + 1),
        scene("03_name", t["name"], "happy",
              [icon_prop("lightbulb", pos, 0.16, c3)], 3.8, idx * 6 + 2),
        scene("04_explain1", t["explain1"], "think",
              [icon_prop(hook_icon, pos, 0.16, c4)], 4.6, idx * 6 + 3),
        scene("05_explain2", t["explain2"], "think",
              [obj_prop(sc1, [0.5, 0.3], 0.44), obj_prop(sc2, [0.3, 0.18], 0.27, t0=0.1),
               obj_prop(sc3, [0.7, 0.18], 0.27, t0=0.15)], 4.6, idx * 6 + 4),
        scene("06_cta", cta_line, "happy",
              [icon_prop("thumbs_up", [0.36, 0.22], 0.15, "#23b26d"),
               icon_prop("bell", [0.64, 0.22], 0.15, "#ffb454")], 4.8, idx * 6 + 5),
    ]
    tags = list(t["keywords"]) + [cfg["niche_tag"], "shorts", "Inklings"]
    hashtags = ["#shorts", f"#{cfg['hashtag']}", f"#{t['slug'].replace('_', '')}", "#inklings"]

    return {
        "title": t["title"],
        "handle": "@Inklings1",
        "hook": t["hook"].upper()[:42],
        "hook_dur": 1.7,
        "style": style,
        "voice": VOICE,
        "scenes": scenes,
        "meta": {"format": "kinetic-typography+scenery", "topic": t["slug"],
                  "tags": tags, "hashtags": hashtags, "comment_prompt": t["comment"]},
    }, t["slug"]


