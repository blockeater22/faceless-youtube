"""Asset packs: versioned, JSON-on-disk bundles of assets.

A pack is the unit of distribution for the marketplace. The format is
deliberately simple so packs can be authored by hand, generated by tooling, or
produced by AI:

    {
      "id": "core",
      "version": "0.1.0",
      "name": "Stickforge Core",
      "description": "...",
      "assets": [ { "id": "...", "type": "...", ... }, ... ]
    }
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from .base import Asset


class PackError(ValueError):
    """Raised for malformed or unreadable packs."""


@dataclass
class AssetPack:
    id: str
    version: str = "0.0.0"
    name: str = ""
    description: str = ""
    assets: list[Asset] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.name:
            self.name = self.id

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "version": self.version,
            "name": self.name,
            "description": self.description,
            "assets": [a.to_dict() for a in self.assets],
        }

    def save(self, path: str | Path) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.to_dict(), indent=2), encoding="utf-8")
        return path


def load_pack(path: str | Path) -> AssetPack:
    """Load and validate an asset pack from a JSON file."""
    path = Path(path)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as e:
        raise PackError(f"pack not found: {path}") from e
    except json.JSONDecodeError as e:
        raise PackError(f"invalid JSON in {path}: {e}") from e

    if "id" not in raw:
        raise PackError(f"pack {path} is missing required 'id'")
    if not isinstance(raw.get("assets", []), list):
        raise PackError(f"pack {path}: 'assets' must be a list")

    pack_id = raw["id"]
    assets: list[Asset] = []
    seen: set[str] = set()
    for i, a in enumerate(raw.get("assets", [])):
        if "id" not in a or "type" not in a:
            raise PackError(
                f"pack {path}: asset #{i} needs both 'id' and 'type'")
        if a["id"] in seen:
            raise PackError(f"pack {path}: duplicate asset id {a['id']!r}")
        seen.add(a["id"])
        asset = Asset.from_dict(a, pack=pack_id)
        asset.validate()
        assets.append(asset)

    return AssetPack(
        id=pack_id,
        version=raw.get("version", "0.0.0"),
        name=raw.get("name", ""),
        description=raw.get("description", ""),
        assets=assets,
    )
